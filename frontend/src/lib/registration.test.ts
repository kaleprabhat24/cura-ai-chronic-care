import { describe, expect, it } from "vitest";
import {
  emptyDraft,
  followUpPreview,
  historyPayload,
  newSubmissionId,
  registrationPayload,
  validateDraft,
  validateHistory,
  type RegistrationDraft,
} from "./registration";

const NOW = new Date("2026-10-15T10:00:00Z");

function valid(): RegistrationDraft {
  const d = emptyDraft();
  return {
    ...d,
    givenName: "Asha",
    familyName: "Testpatient",
    birthDate: "1960-04-02",
    sex: "female",
    deprivation: "3",
    registeredOn: "2015-01-10",
    conditions: { t2d: { enabled: true, onsetDate: "2018-06-01" }, htn: { enabled: false, onsetDate: "" } },
    encounters: [{ type: "review_t2d", startAt: "2026-05-01T09:30:00Z", duration: "20" }],
    observations: [{ kind: "hba1c", value: "8.4", effectiveAt: "2026-05-01T09:40:00Z" }],
    medications: [{ medication: "metformin", startDate: "2018-06-01", endDate: "" }],
  };
}

describe("validateDraft", () => {
  it("accepts a complete fictional patient", () => {
    expect(validateDraft(valid(), NOW)).toEqual({});
  });

  it("rejects bad profile fields", () => {
    const e = validateDraft({ ...valid(), givenName: "4sha", birthDate: "2015-01-01", sex: "", deprivation: "9" }, NOW);
    expect(Object.keys(e).sort()).toEqual(["birthDate", "deprivation", "givenName", "sex"]);
  });

  it("requires a condition, and history only for registered conditions", () => {
    const d = valid();
    d.conditions.t2d.enabled = false;
    const e = validateDraft(d, NOW);
    expect(e.conditions).toBeDefined();
    expect(e["encounters.0"]).toMatch(/condition/);
  });

  it("rejects out-of-range or future observations and inconsistent appointments", () => {
    const d = valid();
    d.observations = [
      { kind: "hba1c", value: "25", effectiveAt: "2026-05-01T09:40:00Z" },
      { kind: "sbp", value: "140", effectiveAt: "2027-01-01T09:40:00Z" },
    ];
    d.appointments = [
      { programme: "t2d", scheduledFor: "2027-01-01T09:00:00Z", status: "attended" },
      { programme: "t2d", scheduledFor: "2026-01-01T09:00:00Z", status: "booked" },
    ];
    const e = validateDraft(d, NOW);
    expect(e["observations.0"]).toMatch(/4–16/);
    expect(e["observations.1"]).toMatch(/future/);
    expect(e["appointments.0"]).toMatch(/future/);
    expect(e["appointments.1"]).toMatch(/outcome/);
  });

  it("rejects medication stop dates before the start", () => {
    const e = validateHistory(
      { appointments: [], encounters: [], observations: [], medications: [{ medication: "metformin", startDate: "2026-02-01", endDate: "2026-01-01" }] },
      NOW,
      new Set(["t2d"]),
    );
    expect(e["medications.0"]).toBeDefined();
  });
});

describe("payloads", () => {
  it("builds the registration body with UCUM units and UTC timestamps", () => {
    const body = registrationPayload(valid(), "0f8fad5b-d9cb-469f-a165-70867728950e");
    expect(body.submission_id).toBe("0f8fad5b-d9cb-469f-a165-70867728950e");
    expect(body.conditions).toEqual([{ programme: "t2d", onset_date: "2018-06-01" }]);
    expect(body.history.observations?.[0]).toEqual({ kind: "hba1c", value: 8.4, unit: "%", effective_at: "2026-05-01T09:40:00.000Z" });
    expect(body.history.medications?.[0].end_date).toBeNull();
    expect(body.allow_possible_duplicate).toBe(false);
    expect(JSON.stringify(body)).not.toMatch(/"id"/); // ids are generated by the server
  });

  it("history payload maps encounter fields", () => {
    const h = historyPayload(valid());
    expect(h.encounters?.[0]).toEqual({ encounter_type: "review_t2d", start_at: "2026-05-01T09:30:00.000Z", duration_minutes: 20 });
  });

  it("generates distinct UUID submission ids", () => {
    const a = newSubmissionId();
    expect(a).toMatch(/^[0-9a-f-]{36}$/);
    expect(newSubmissionId()).not.toBe(a);
  });
});

describe("followUpPreview", () => {
  it("uses the latest review and the programme interval", () => {
    const d = valid();
    d.appointments = [{ programme: "t2d", scheduledFor: "2026-06-01T09:00:00Z", status: "attended" }];
    expect(followUpPreview(d, "t2d")).toEqual({ lastReview: "2026-06-01", due: "2026-11-30", predictionAt: "2026-11-16" });
  });

  it("returns null without a completed review", () => {
    const d = valid();
    d.encounters = [];
    expect(followUpPreview(d, "t2d")).toBeNull();
  });
});
