"""Model report and model card (Markdown), generated from stored training/evaluation results."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from cura_ml.features import spec as S

NAMES = {"prevalence_baseline": "Prevalence baseline", "attendance_heuristic": "Attendance heuristic",
         "logistic_regression": "Logistic regression", "xgboost": "XGBoost"}
BANNER = ("> **Synthetic-data evaluation, not clinical validation.** All patients, events and outcomes "
          "are simulated. These numbers describe how well the models recover structure that the "
          "simulator put into the data. They are not evidence of real-world performance or clinical benefit.")


def _f(x: float, d: int = 3) -> str:
    return "–" if x != x else f"{x:.{d}f}"


def _ci(ci: list[float], d: int = 3) -> str:
    return f"[{ci[0]:.{d}f}, {ci[1]:.{d}f}]"


def _table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def model_card(md: dict[str, Any], ev: dict[str, Any]) -> str:
    sel = md["model_type"]
    t = ev["test"]["point"][sel]
    ci = ev["test"]["bootstrap"]["models"][sel]
    primary = f"{md['training_config']['capacity']['primary_fraction']:.2f}"
    return f"""# Model card — {md['model_version']}

{BANNER}

## Model
- **Type:** {NAMES[sel]} (selected by a pre-declared validation rule; see the model report)
- **Prediction target:** {md['prediction_target']}.
- **Output:** calibrated probability ({md['calibration_method']} calibration fitted on validation data),
  a risk tier (High ≥ {md['tier_thresholds']['high']:.3f}, Medium ≥ {md['tier_thresholds']['medium']:.3f}),
  and per-prediction explanations ({md['explanation_method']}, log-odds contributions).
- **Features:** {len(md['feature_columns'])} columns, feature spec {md['feature_spec_version']}
  (see `feature_spec.json`). All features are computed from records recorded before the prediction time.

## Intended use
Ranking eligible chronic-care follow-ups for outreach in a **demonstration** application on synthetic data.
The model predicts follow-up non-completion. It does **not** predict disease deterioration, and it does
not diagnose or recommend treatment.

## Not intended for
Clinical decision-making, real patients, or any claim of real-world effectiveness.

## Training data
Synthetic cohort `{md['cohort_config']['dataset_version']}`
(data fingerprint `{md['data_fingerprint'][:16]}…`).
Trained on {md['trained_on']['episodes']:,} episodes from {md['trained_on']['years']}; calibrated on
{md['calibrated_on']['episodes']:,} validation episodes. Tested on held-out patients in
{md['training_config']['splits']['test_year']}.

## Test results (held-out patients, synthetic)
PR-AUC {_f(t['pr_auc'])} {_ci(ci['pr_auc'])}, ROC-AUC {_f(t['roc_auc'])} {_ci(ci['roc_auc'])},
Brier {_f(t['brier'])} {_ci(ci['brier'])}, precision at {float(primary):.0%} capacity
{_f(t['capacity'][primary]['precision'])} {_ci(ci['precision_at_capacity'])}, calibration slope
{_f(t['calibration_slope'], 2)}, ECE {_f(t['ece'])}. Test prevalence {_f(t['prevalence'])} (n = {t['n']:,}).

## Explanations
Contributions are on the log-odds scale of the uncalibrated model. They are not percentages of risk.
They show which recorded data the model relied on. They are associations, not causes.

## Limitations
- Synthetic data generated by a simplified simulator; real-world relationships will differ.
- The label reflects outcomes under the simulated historical outreach policy. It is not a causal
  estimate of what outreach achieves.
- Performance can drift. Re-evaluate on new data before reuse. Check the feature spec and
  library versions in `metadata.json`.
"""


def write_model_report(path: str | Path, md: dict[str, Any], ev: dict[str, Any]) -> Path:
    path = Path(path)
    sel = ev["selected_model"]
    cfg = md["training_config"]
    primary = f"{cfg['capacity']['primary_fraction']:.2f}"
    w: list[str] = [f"# Cura AI follow-up risk model — {md['model_version']}\n", BANNER + "\n"]

    w.append("## Summary\n")
    sel_t = ev["test"]["point"][sel]
    w.append(f"- Selected model: **{NAMES[sel]}** ({md['calibration_method']} calibration). "
             f"Selection rule (validation calibration half only): {ev['selection']['rule']}. "
             f"Observed validation difference XGBoost − LR: PR-AUC "
             f"{ev['selection']['xgboost_minus_lr_val_pr_auc']:+.4f} "
             f"{_ci(ev['selection']['xgboost_minus_lr_val_pr_auc_ci'], 4)}, Brier "
             f"{ev['selection']['xgboost_minus_lr_val_brier']:+.4f}.\n"
             f"- Test (held-out patients, {cfg['splits']['test_year']}): "
             f"PR-AUC {_f(sel_t['pr_auc'])}, ROC-AUC "
             f"{_f(sel_t['roc_auc'])}, Brier {_f(sel_t['brier'])}, precision at "
             f"{float(primary):.0%} capacity {_f(sel_t['capacity'][primary]['precision'])} vs prevalence "
             f"{_f(sel_t['prevalence'])}.\n"
             f"- Test patients overlapping training/validation patients: "
             f"{ev['test_patients_overlapping_training_or_validation']}.\n")

    w.append("## Evaluation design and splits\n")
    w.append(f"Patients are split 80/20 at random (seed {cfg['seed']}); the 20% held-out patients are used "
             f"only for the final test. Train: {cfg['splits']['train_years']}. Validation: "
             f"{cfg['splits']['validation_year']}, split by patient into a tuning half (hyper-parameters, "
             f"early stopping) and a calibration half (calibration, model selection, tier thresholds). "
             f"Test: {cfg['splits']['test_year']}, held-out patients. Training labels matured before the "
             f"validation year began; validation labels before the test year began.\n")
    w.append(_table(["split", "episodes", "patients", "prevalence"],
                    [[s, f"{v['episodes']:,}", f"{v['patients']:,}", _f(v['prevalence'])]
                     for s, v in ev["splits"].items()]))

    w.append("## Label prevalence over time (all labelled episodes)\n")
    years = sorted({r["year"] for r in ev["label_prevalence_over_time"]})
    by = {(r["year"], r["programme"]): r for r in ev["label_prevalence_over_time"]}
    w.append(_table(["year", "labelled", "all", "t2d", "htn"],
                    [[y, f"{by[(y, 'all')]['labelled']:,}", _f(by[(y, 'all')]['prevalence']),
                      _f(by[(y, 't2d')]['prevalence']), _f(by[(y, 'htn')]['prevalence'])] for y in years]))

    w.append("## Model comparison — test set (held-out patients)\n")
    w.append(f"95% intervals from a patient-level bootstrap ({ev['test']['bootstrap']['n_resamples_used']} "
             f"resamples). Ranking metrics use raw model scores (the worklist order); Brier/calibration "
             f"use calibrated probabilities. Capacity = top {float(primary):.0%} of episodes.\n")
    rows = []
    for n in NAMES:
        p, c = ev["test"]["point"][n], ev["test"]["bootstrap"]["models"][n]
        rows.append([NAMES[n] + (" **(selected)**" if n == sel else ""),
                     f"{_f(p['pr_auc'])} {_ci(c['pr_auc'])}", f"{_f(p['roc_auc'])} {_ci(c['roc_auc'])}",
                     f"{_f(p['brier'])} {_ci(c['brier'])}",
                     f"{_f(p['capacity'][primary]['precision'])} {_ci(c['precision_at_capacity'])}",
                     f"{_f(p['capacity'][primary]['recall'])} {_ci(c['recall_at_capacity'])}",
                     _f(p["ece"]), _f(p["calibration_slope"], 2)])
    w.append(_table(["model", "PR-AUC", "ROC-AUC", "Brier", "precision@cap", "recall@cap", "ECE",
                     "cal. slope"], rows))
    w.append("### Paired differences (test, bootstrap)\n")
    w.append(_table(["comparison", "Δ PR-AUC [95% CI]", "Δ ROC-AUC [95% CI]", "Δ Brier [95% CI]",
                     "Δ precision@cap [95% CI]"],
                    [[k.replace("_", " "), _ci(d["pr_auc"]["interval"]), _ci(d["roc_auc"]["interval"]),
                      _ci(d["brier"]["interval"], 4), _ci(d["precision_at_capacity"]["interval"])]
                     for k, d in ev["test"]["bootstrap"]["differences"].items()]))
    w.append("### Precision / recall / lift at other capacities (test)\n")
    rows = []
    for n in NAMES:
        for fr, m in ev["test"]["point"][n]["capacity"].items():
            rows.append([NAMES[n], f"{float(fr):.0%}", m["k"], _f(m["precision"]), _f(m["recall"]),
                         _f(m["lift"], 2)])
    w.append(_table(["model", "capacity", "k", "precision", "recall", "lift"], rows))

    w.append("## Validation results (calibration half — used for selection)\n")
    w.append(_table(["model", "PR-AUC", "ROC-AUC", "Brier", "ECE", "calibration"],
                    [[NAMES[n], _f(v["pr_auc"]), _f(v["roc_auc"]), _f(v["brier"]), _f(v["ece"]),
                      ev["calibration"]["chosen"][n]] for n, v in ev["validation"].items()]))
    t = ev["tuning"]
    lr_grid = ", ".join(f"C={r['C']}: {r['val_tune_pr_auc']:.3f}" for r in t["logistic_regression"])
    xgb_grid = ", ".join(f"depth {r['max_depth']}: {r['val_tune_pr_auc']:.3f} @ {r['n_estimators']} trees"
                         for r in t["xgboost"])
    cal_cv = "; ".join(f"{NAMES[n]} " + ", ".join(f"{m} {b:.4f}" for m, b in cv.items())
                       for n, cv in ev["calibration"]["cv_brier"].items())
    best = t["xgboost_best"]
    w.append(f"Tuning on the validation tuning half: logistic regression C = "
             f"{t['logistic_regression_best_C']} (grid PR-AUC: {lr_grid}); XGBoost max_depth = "
             f"{best['max_depth']}, trees = {best['n_estimators']} (grid: {xgb_grid}). Calibration methods "
             f"chosen by patient-grouped 5-fold CV Brier on the calibration half: {cal_cv}.\n")

    w.append(f"## Calibration — {NAMES[sel]} on the test set\n")
    w.append(f"ECE {_f(sel_t['ece'])}, calibration slope {_f(sel_t['calibration_slope'], 2)}, intercept "
             f"{_f(sel_t['calibration_intercept'], 2)}, calibration-in-the-large (observed − mean predicted) "
             f"{sel_t['calibration_in_the_large']:+.3f}.\n")
    w.append(_table(["decile", "n", "mean predicted", "observed rate"],
                    [[i + 1, r["n"], _f(r["mean_predicted"]), _f(r["observed_rate"])]
                     for i, r in enumerate(ev["test"]["calibration_table"])]))
    th = ev["tier_thresholds"]
    w.append(f"Risk-tier thresholds (fixed on validation): High ≥ {th['high']:.3f}, "
             f"Medium ≥ {th['medium']:.3f}.\n")
    w.append(_table(["tier", "test episodes", "share", "observed incomplete rate"],
                    [[r["tier"], r["n"], _f(r["share"]), _f(r["observed_incomplete_rate"])]
                     for r in ev["test"]["tiers"]]))

    w.append("## Feature importance (test set, mean |contribution|, log-odds)\n")
    w.append("Feature and missing-indicator contributions are combined. Values are model-specific and "
             "not comparable as percentages of risk.\n")
    lr_imp = ev["feature_importance"]["logistic_regression"]["features"][:12]
    xg_imp = {r["feature"]: r for r in ev["feature_importance"]["xgboost"]["features"]}
    w.append(_table(["feature", "label", "LR mean |contribution|", "XGBoost mean |SHAP|"],
                    [[f"`{r['feature']}`", r["label"], _f(r["mean_abs_log_odds"]),
                      _f(xg_imp[r["feature"]]["mean_abs_log_odds"])] for r in lr_imp]))
    xg_top = ", ".join(f"`{r['feature']}`" for r in ev["feature_importance"]["xgboost"]["features"][:8])
    w.append(f"XGBoost top features: {xg_top}. SHAP check: max |shap − XGBoost native contributions| = "
             f"{ev['shap_consistency']['max_abs_diff_shap_vs_xgboost_native']:.2e}; additivity error "
             f"{ev['shap_consistency']['max_abs_additivity_error']:.2e}.\n")

    ex = ev.get("example_explanation")
    if ex:
        w.append("## Example explanation (highest-scored test episode)\n")
        w.append(f"Episode `{ex['episode_id']}` — calibrated probability {ex['calibrated_probability']:.3f} "
                 f"(tier {ex['risk_tier']}); model log-odds {ex['model_log_odds']:+.3f} = base "
                 f"{ex['base_log_odds']:+.3f} + contributions. {ex['units']}\n")
        w.append(_table(["factor", "recorded value", "contribution (log-odds)", "direction"],
                        [[f["label"], f["value_text"],
                          f"{f['contribution_log_odds']:+.3f}", f["direction"]] for f in ex["factors"]]))
        w.append(ex["note"] + "\n")

    w.append("## Leakage checks\n")
    w.append("Single-feature discrimination on the training set (max(AUC, 1 − AUC)); features ≥ "
             f"{cfg['evaluation']['suspicious_single_feature_auc']} would be investigated as possible leaks. "
             f"Flagged: {ev['suspicious_features'] or 'none'}.\n")
    w.append(_table(["feature", "single-feature AUC"],
                    [[f"`{n}`", _f(a)] for n, a in ev["single_feature_auc_train"][:8]]))

    w.append("## Missing data (share of episodes with the feature missing)\n")
    miss = ev["feature_missingness"]
    rows = [[f"`{c}`", _f(miss["train"][c]), _f(miss["test"][c])]
            for c in miss["train"] if miss["train"][c] > 0 or miss["test"][c] > 0]
    w.append(_table(["feature", "train", "test"], rows))
    w.append("HbA1c features are missing by design for hypertension-only patients, and for diabetes "
             "patients whose HbA1c was not drawn or not resulted. Booking features are missing when no "
             "review is booked.\n")

    w.append(f"## Subgroups — {NAMES[sel]}, test set\n")
    w.append(_table(["group", "value", "n", "prevalence", "PR-AUC", "mean predicted"],
                    [[r["group"], r["value"], r["n"], _f(r["prevalence"]), _f(r["pr_auc"]),
                      _f(r["mean_predicted"])] for r in ev["subgroups_test"]]))
    w.append("Subgroup samples are small; differences are descriptive only.\n")

    w.append("## Limitations\n")
    w.append("- Synthetic data: the simulator determines every relationship, so the results show "
             "methodology, not clinical validity.\n"
             "- Labels reflect the simulated historical outreach policy; predictions are not causal "
             "estimates of the effect of outreach.\n"
             f"- The test set is one year of held-out patients (n = {sel_t['n']:,}); intervals are wide "
             "for small subgroups.\n"
             "- Explanations are model contributions (log-odds), not causes and not risk percentages.\n"
             f"- Feature spec {S.FEATURE_SPEC_VERSION}; any change to features or data requires retraining "
             "and re-evaluation.\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(w), encoding="utf-8")
    return path
